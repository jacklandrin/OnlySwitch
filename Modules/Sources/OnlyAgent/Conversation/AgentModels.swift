import Foundation

public enum AgentScriptKind: String, Codable, Sendable, Equatable, CaseIterable {
    case applescript
    case shell
}

public enum AgentStepStatus: Equatable, Sendable {
    case pending
    case running
    case succeeded
    case failed
    case stopped
    case skipped
}

public struct AgentScriptStep: Identifiable, Equatable, Sendable {
    public var id: UUID
    public var title: String
    public var kind: AgentScriptKind
    public var code: String
    public var status: AgentStepStatus
    public var output: String?
    public var error: String?

    public init(
        id: UUID,
        title: String,
        kind: AgentScriptKind,
        code: String,
        status: AgentStepStatus = .pending,
        output: String? = nil,
        error: String? = nil
    ) {
        self.id = id
        self.title = title
        self.kind = kind
        self.code = code
        self.status = status
        self.output = output
        self.error = error
    }
}

public struct AgentPlan: Identifiable, Equatable, Sendable {
    public var id: UUID
    public var title: String
    public var summary: String
    public var steps: [AgentScriptStep]

    public init(id: UUID, title: String, summary: String, steps: [AgentScriptStep]) {
        self.id = id
        self.title = title
        self.summary = summary
        self.steps = steps
    }

    public var isSucceeded: Bool {
        !steps.isEmpty && steps.allSatisfy { $0.status == .succeeded }
    }

    public var isRunning: Bool {
        steps.contains { $0.status == .running }
    }

    public var hasFailed: Bool {
        steps.contains { $0.status == .failed || $0.status == .stopped }
    }

    public var hasRun: Bool {
        steps.contains { $0.status != .pending }
    }
}

public struct AgentQuestion: Identifiable, Equatable, Sendable {
    public var id: UUID
    public var prompt: String
    public var options: [String]
    public var answer: String

    public init(id: UUID, prompt: String, options: [String], answer: String = "") {
        self.id = id
        self.prompt = prompt
        self.options = options
        self.answer = answer
    }
}

public enum AgentReply: Equatable, Sendable {
    case questions([AgentQuestion])
    case plan(AgentPlan)
    case message(String)
}

public enum AgentExecutionMode: String, Codable, Sendable, CaseIterable {
    case preview
    case direct
}

public enum AgentNotice: Equatable, Sendable {
    case selectModel
}

public struct AgentMessage: Identifiable, Equatable, Sendable {
    public enum Role: Equatable, Sendable {
        case user
        case assistant
    }

    public enum Content: Equatable, Sendable {
        case text(String)
        case questions([AgentQuestion], answered: Bool)
        case plan(AgentPlan)
        case error(String)
        /// A notice generated by Only Agent itself; localized by the view.
        case notice(AgentNotice)
        /// The user asked the agent to fix a failed plan.
        case fixRequest
    }

    public var id: UUID
    public var role: Role
    public var content: Content

    public init(id: UUID, role: Role, content: Content) {
        self.id = id
        self.role = role
        self.content = content
    }
}
